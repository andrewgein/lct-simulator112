    WHEN 'DDS_SERVICE_POLICE' THEN 'POLICE'
    WHEN 'DDS_SERVICE_AMBULANCE' THEN 'AMBULANCE'
    WHEN 'FIRE' THEN 'MCHS'
    WHEN 'GAS' THEN 'MOSGAZ'
    WHEN 'ANTI_TERROR' THEN 'FSB'
    ELSE service_code
END
WHERE service_code IN ('DDS_SERVICE_FIRE', 'DDS_SERVICE_GAS', 'DDS_SERVICE_ANTI_TERROR', 'DDS_SERVICE_POLICE', 'DDS_SERVICE_AMBULANCE', 'FIRE', 'GAS', 'ANTI_TERROR');

